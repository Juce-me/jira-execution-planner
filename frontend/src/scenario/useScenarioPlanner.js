import { useScenarioDraft } from './useScenarioDraft.js';
import { useScenarioRealtime } from './useScenarioRealtime.js';
import { useScenarioDerived } from './useScenarioDerived.js';
import { useScenarioDrag } from './useScenarioDrag.js';
import { useScenarioHistory } from './useScenarioHistory.js';
import { useScenarioLayout } from './useScenarioLayout.js';

export function useScenarioPlanner({
    scenarioState,
    BACKEND_URL,
    EMPTY_ARRAY,
    EMPTY_OBJECT,
    perfEnabled,
    perfCountersRef,
    pendingConnectionRecoveryRef,
    releaseConnectionRecoveryOwnership,
    connectionRecoveryScenarioStartedRef,
    setConnectionRecoveryNotice,
    setConnectionRecoveryStatus,
    connectionRecoveryStagedRevision,
    selectedSprint,
    availableSprints,
    sprintsLoading,
    groupsLoading,
    activeGroupId,
    jiraUrl,
    showScenario,
    searchQuery,
    pendingShellAuthResumeRef,
    selectedSprintInfo,
    trackScenarioAction,
    visibleControlGroups,
    selectedSprintState,
    isCompletedSprintSelected,
    normalizeEpicKey,
    registerSprintFetch,
    cleanupSprintFetch,
    activeGroup,
    teamOptions,
    selectedTeamSet,
    isAllTeamsSelected,
    excludedEpicSet,
}) {
    const {
        fetchScenarioDraft,
        pauseScenarioRealtime,
        postScenarioRealtimeJson,
        pollScenarioDraftEvents,
        saveScenarioDraftVersion,
        fetchScenarioDraftVersion,
        rollbackScenarioDraft,
        reloadScenarioDraftFromJira,
        buildScenarioDraftScope,
        runScenario,
        scenarioScopeKey,
        scenarioHasUnsavedChanges,
        scenarioCanSaveDraft,
        scenarioActiveDraftId,
        isScenarioScopeDraftCurrent,
        scenarioActiveDraftReady,
    } = useScenarioDraft({
        scenarioState,
        BACKEND_URL,
        pendingConnectionRecoveryRef,
        releaseConnectionRecoveryOwnership,
        connectionRecoveryScenarioStartedRef,
        setConnectionRecoveryNotice,
        setConnectionRecoveryStatus,
        connectionRecoveryStagedRevision,
        selectedSprint,
        availableSprints,
        sprintsLoading,
        groupsLoading,
        activeGroupId,
        showScenario,
        pendingShellAuthResumeRef,
        selectedSprintInfo,
        trackScenarioAction,
        visibleControlGroups,
        selectedSprintState,
        isCompletedSprintSelected,
        registerSprintFetch,
        cleanupSprintFetch,
        activeGroup,
        teamOptions,
        selectedTeamSet,
        isAllTeamsSelected,
        excludedEpicSet,
    });

    const {
        acquireScenarioIssueLock,
        refreshScenarioIssueLock,
        releaseScenarioIssueLock,
        scenarioRemoteEditors,
        scenarioIssueLockWarnings,
    } = useScenarioRealtime({
        scenarioState,
        BACKEND_URL,
        pauseScenarioRealtime,
        postScenarioRealtimeJson,
        pollScenarioDraftEvents,
        scenarioScopeKey,
        scenarioActiveDraftId,
        scenarioActiveDraftReady,
    });

    const {
        scenarioSummary,
        scenarioBaseUrl,
        scenarioDependencies,
        scenarioCapacityByTeam,
        scenarioIssues,
        scenarioSearchQuery,
        scenarioSearchMatchSet,
        scenarioExcludedIssueKeys,
        scenarioFocusSet,
        scenarioContextSet,
        scenarioIssueByKey,
        scenarioDeadline,
        scenarioViewStart,
        scenarioViewEnd,
        scenarioFocusIssueKeys,
        scenarioFocusContextKeys,
        scenarioTimelineIssues,
        scenarioTimelineWithSegments,
        scenarioTimelineIssueKeys,
        scenarioAssigneeConflicts,
        scenarioDepViolations,
        scenarioDepViolatedKeys,
    } = useScenarioDerived({
        scenarioState,
        EMPTY_ARRAY,
        EMPTY_OBJECT,
        jiraUrl,
        searchQuery,
        normalizeEpicKey,
        excludedEpicSet,
    });

    // --- Drag effect, undo/redo, save/discard (placed after scenarioViewStart/End & scenarioIssueByKey) ---

    const {
        toggleScenarioEditMode,
        handleScenarioBarMouseDown,
        scenarioUndo,
        scenarioRedo,
        scenarioOverrideCount,
    } = useScenarioDrag({
        scenarioState,
        trackScenarioAction,
        scenarioHasUnsavedChanges,
        acquireScenarioIssueLock,
        refreshScenarioIssueLock,
        releaseScenarioIssueLock,
        scenarioIssueByKey,
    });

    const {
        saveScenarioDraft,
        discardScenarioOverrides,
        openScenarioDraftHistory,
        closeScenarioDraftHistory,
        requestReloadActiveDraft,
        cancelReloadActiveDraft,
        runReloadActiveDraft,
        requestScenarioHistoryAction,
        cancelScenarioHistoryAction,
        requestScenarioReloadFromJira,
        cancelScenarioReloadFromJira,
        runScenarioReloadFromJira,
        previewScenarioDraftWriteback,
        checkScenarioDraftWritebackGate,
        runScenarioHistoryAction,
    } = useScenarioHistory({
        scenarioState,
        trackScenarioAction,
        fetchScenarioDraft,
        postScenarioRealtimeJson,
        saveScenarioDraftVersion,
        fetchScenarioDraftVersion,
        rollbackScenarioDraft,
        reloadScenarioDraftFromJira,
        buildScenarioDraftScope,
        scenarioScopeKey,
        scenarioHasUnsavedChanges,
        scenarioCanSaveDraft,
        isScenarioScopeDraftCurrent,
    });

    const {
        registerScenarioIssueRef,
        scenarioLaneInfo,
        scenarioLateItems,
        scenarioDeadlineAtRisk,
        scenarioCriticalPathItems,
        scenarioUnschedulableItems,
        scenarioIssuesByLane,
        scenarioTicks,
        scenarioQuarterMarkers,
        SCENARIO_LANE_HEIGHT,
        scenarioBarGap,
        scenarioJiraEpicKeys,
        scenarioJiraStoryKeys,
        scenarioLaneMeta,
        scenarioLaneAssigneeGroups,
        scenarioPositions,
        scenarioEpicBars,
        scenarioEpicEdges,
        scenarioTodayLeft,
        scenarioVisibleLanes,
        scenarioUpstreamSet,
        scenarioDownstreamSet,
        scenarioBlockedSet,
        toggleScenarioLane,
        showScenarioTooltip,
        showScenarioTooltipFromElement,
        moveScenarioTooltip,
        hideScenarioTooltip,
        clearScenarioEpicFocus,
        focusScenarioEpic,
        scrollToScenarioIssue,
    } = useScenarioLayout({
        scenarioState,
        perfEnabled,
        perfCountersRef,
        showScenario,
        normalizeEpicKey,
        isAllTeamsSelected,
        excludedEpicSet,
        scenarioSummary,
        scenarioDependencies,
        scenarioCapacityByTeam,
        scenarioIssues,
        scenarioSearchQuery,
        scenarioSearchMatchSet,
        scenarioExcludedIssueKeys,
        scenarioFocusSet,
        scenarioContextSet,
        scenarioIssueByKey,
        scenarioDeadline,
        scenarioViewStart,
        scenarioViewEnd,
        scenarioFocusIssueKeys,
        scenarioFocusContextKeys,
        scenarioTimelineIssues,
        scenarioTimelineWithSegments,
        scenarioTimelineIssueKeys,
        scenarioAssigneeConflicts,
    });
    return {
        registerScenarioIssueRef,
        runScenario,
        toggleScenarioEditMode,
        handleScenarioBarMouseDown,
        scenarioBaseUrl,
        scenarioHasUnsavedChanges,
        scenarioCanSaveDraft,
        scenarioRemoteEditors,
        scenarioIssueLockWarnings,
        scenarioSearchQuery,
        scenarioSearchMatchSet,
        scenarioIssueByKey,
        scenarioViewStart,
        scenarioViewEnd,
        scenarioFocusIssueKeys,
        scenarioFocusContextKeys,
        scenarioAssigneeConflicts,
        scenarioDepViolations,
        scenarioDepViolatedKeys,
        scenarioUndo,
        scenarioRedo,
        scenarioOverrideCount,
        saveScenarioDraft,
        discardScenarioOverrides,
        openScenarioDraftHistory,
        closeScenarioDraftHistory,
        requestReloadActiveDraft,
        cancelReloadActiveDraft,
        runReloadActiveDraft,
        requestScenarioHistoryAction,
        cancelScenarioHistoryAction,
        requestScenarioReloadFromJira,
        cancelScenarioReloadFromJira,
        runScenarioReloadFromJira,
        previewScenarioDraftWriteback,
        checkScenarioDraftWritebackGate,
        runScenarioHistoryAction,
        scenarioLaneInfo,
        scenarioLateItems,
        scenarioDeadlineAtRisk,
        scenarioCriticalPathItems,
        scenarioUnschedulableItems,
        scenarioIssuesByLane,
        scenarioTicks,
        scenarioQuarterMarkers,
        SCENARIO_LANE_HEIGHT,
        scenarioBarGap,
        scenarioJiraEpicKeys,
        scenarioJiraStoryKeys,
        scenarioLaneMeta,
        scenarioLaneAssigneeGroups,
        scenarioPositions,
        scenarioEpicBars,
        scenarioEpicEdges,
        scenarioTodayLeft,
        scenarioVisibleLanes,
        scenarioUpstreamSet,
        scenarioDownstreamSet,
        scenarioBlockedSet,
        toggleScenarioLane,
        showScenarioTooltip,
        showScenarioTooltipFromElement,
        moveScenarioTooltip,
        hideScenarioTooltip,
        clearScenarioEpicFocus,
        focusScenarioEpic,
        scrollToScenarioIssue,
    };
}
